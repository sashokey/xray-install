check_domain_dns() {
    local records
    records="$(dig +time=3 +tries=2 +short A "$PROJECT_DOMAIN")"
    [[ -n "$records" ]] || fail "No public A record found for $PROJECT_DOMAIN."
    records="$(dig +time=3 +tries=2 +noall +answer AAAA "$PROJECT_DOMAIN" | awk '$4 == "AAAA" {print $5}')"
    [[ -z "$records" ]] || fail 'Remove the slave domain AAAA record; this installer listens on IPv4.'
    python3 - "$TEMP_DIR/main-outbound.json" <<'PY'
import json
import socket
import subprocess
import sys

main = json.load(open(sys.argv[1], encoding='utf-8'))['settings']['vnext'][0]
addresses = {item[4][0] for item in socket.getaddrinfo(main['address'], main['port'], type=socket.SOCK_STREAM)}
local = {'127.0.0.1', '::1'}
for interface in json.loads(subprocess.check_output(['ip', '-j', 'address', 'show'])):
    local.update(address['local'] for address in interface.get('addr_info', []))
if addresses & local:
    raise SystemExit('ERROR: The main server address resolves to this slave; refusing a proxy loop.')
PY
}

