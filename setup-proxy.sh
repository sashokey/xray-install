switch_release() {
    ln -s "$1" "$RELEASE_ROOT/current.next.$$" || return
    mv -Tf "$RELEASE_ROOT/current.next.$$" "$RELEASE_ROOT/current"
}

install_release() {
    local destination="$RELEASE_ROOT/releases/$XRAY_VERSION"
    install -d -m 755 "$RELEASE_ROOT/releases"
    if [[ ! -d "$destination" ]]; then
        install -d -m 755 "$destination"
        install -m 755 "$TEMP_DIR/release/xray" "$destination/xray"
    else
        cmp -s "$TEMP_DIR/release/xray" "$destination/xray" || fail 'The saved release differs from the verified download.'
    fi
}

check_fallback() {
    local status
    status="$(curl -4 --noproxy '*' --silent --show-error --http2 --connect-timeout 2 --max-time 5 \
        --resolve "$PROJECT_DOMAIN:443:127.0.0.1" "https://$PROJECT_DOMAIN/" \
        -o "$TEMP_DIR/fallback.html" -w '%{http_code}')" || return
    [[ "$status" == 403 ]] && grep -q '<title>403 Forbidden</title>' "$TEMP_DIR/fallback.html"
}

wait_for_xray() {
    local attempt
    for ((attempt = 0; attempt < 10; attempt++)); do
        if systemctl is-active --quiet "$SERVICE" && check_fallback; then
            return 0
        fi
        sleep 0.3
    done
    return 1
}

write_probe_client() {
    python3 - "$PROJECT_DOMAIN" "$VLESS_CLIENT_UUID" "$TEMP_DIR/slave-outbound.json" <<'PY'
import json
import sys
from pathlib import Path

domain, identity, target = sys.argv[1:]
outbound = {
    'tag': 'slave', 'protocol': 'vless',
    'settings': {'vnext': [{'address': '127.0.0.1', 'port': 443, 'users': [
        {'id': identity, 'encryption': 'none', 'flow': 'xtls-rprx-vision'}
    ]}]},
    'streamSettings': {
        'network': 'raw', 'security': 'tls',
        'tlsSettings': {'serverName': domain, 'alpn': ['h2'], 'fingerprint': 'firefox', 'allowInsecure': False}
    },
    'mux': {'enabled': False}
}
Path(target).write_text(json.dumps(outbound, indent=2) + '\n', encoding='utf-8')
PY
}

verify_chain() {
    local binary="$RELEASE_ROOT/current/xray" direct_exit chained_exit
    wait_for_xray || return
    write_probe_client || return
    direct_exit="$(probe_outbound "$binary" "$TEMP_DIR/main-outbound.json")" || return
    chained_exit="$(probe_outbound "$binary" "$TEMP_DIR/slave-outbound.json")" || return
    [[ "$chained_exit" == "$direct_exit" ]] || { printf 'ERROR: Main and chained exit IPs differ.\n' >&2; return 1; }
    printf 'Verified client -> slave -> main. Exit IPv4: %s\n' "$chained_exit"
}

install_service() {
    local previous='' had_config=0 was_active=0
    [[ ! -L "$RELEASE_ROOT/current" ]] || previous="$(readlink -f "$RELEASE_ROOT/current")"
    if [[ -f "$CONFIG_DIR/config.json" ]]; then
        cp "$CONFIG_DIR/config.json" "$TEMP_DIR/previous-config.json"
        had_config=1
    fi
    systemctl is-active --quiet "$SERVICE" && was_active=1
    install_release
    install -d -m 700 "$CONFIG_DIR"
    install -m 600 "$TEMP_DIR/config.json" "$CONFIG_DIR/config.json.next"
    mv -f "$CONFIG_DIR/config.json.next" "$CONFIG_DIR/config.json"
    cat > /etc/systemd/system/xray-proxy.service <<'EOF'
[Unit]
Description=Xray VLESS proxy to main
After=network-online.target nss-lookup.target
Wants=network-online.target
StartLimitIntervalSec=0
[Service]
Type=simple
User=root
UMask=0077
ExecStart=/usr/local/lib/xray-proxy/current/xray run -config /usr/local/etc/xray-proxy/config.json
Restart=on-failure
RestartSec=2
LimitNOFILE=1048576
[Install]
WantedBy=multi-user.target
EOF
    chmod 644 /etc/systemd/system/xray-proxy.service
    systemctl daemon-reload
    switch_release "$RELEASE_ROOT/releases/$XRAY_VERSION"
    if systemctl is-failed --quiet "$SERVICE"; then
        systemctl reset-failed "$SERVICE"
    fi
    if systemctl restart "$SERVICE" && verify_chain; then
        systemctl enable "$SERVICE"
        install -m 600 "$TEMP_DIR/main-outbound.json" "$STATE_DIR/main-outbound.json"
        printf '%s\n' "$PROJECT_DOMAIN" > "$STATE_DIR/domain"
        printf '%s\n' "$VLESS_CLIENT_UUID" > "$STATE_DIR/client-uuid"
    else
        systemctl stop "$SERVICE" || true
        if [[ "$had_config" == 1 && -n "$previous" ]]; then
            install -m 600 "$TEMP_DIR/previous-config.json" "$CONFIG_DIR/config.json"
            switch_release "$previous"
            if [[ "$was_active" == 1 ]]; then
                systemctl restart "$SERVICE" || fail 'The new setup and service rollback failed.'
            fi
        fi
        fail 'The chain check failed. The previous Xray configuration was restored when available. Certificates were kept.'
    fi
}

