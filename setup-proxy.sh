    cat > /etc/letsencrypt/renewal-hooks/deploy/xray-proxy <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
domain="$(cat /var/lib/xray-proxy-setup/domain)"
if [[ "${RENEWED_LINEAGE:-}" == "/etc/letsencrypt/live/$domain" ]]; then
    /usr/local/lib/xray-proxy/current/xray run -test -config /usr/local/etc/xray-proxy/config.json
    systemctl try-restart xray-proxy.service
fi
EOF
    chmod 700 /etc/letsencrypt/renewal-hooks/deploy/xray-proxy
    printf 'SHELL=/bin/bash\nPATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n@daily root /usr/local/sbin/xray-proxy-setup --update 2>&1 | /usr/bin/logger -t xray-proxy-update\n' > /etc/cron.d/xray-proxy-update
    chmod 644 /etc/cron.d/xray-proxy-update
    systemctl enable --now certbot.timer cron
}

load_installation() {
    [[ -f "$STATE_DIR/domain" && -f "$STATE_DIR/client-uuid" && -f "$STATE_DIR/main-outbound.json" ]] || fail 'No completed proxy installation found.'
    PROJECT_DOMAIN="$(cat "$STATE_DIR/domain")"
    VLESS_CLIENT_UUID="$(cat "$STATE_DIR/client-uuid")"
    validate_domain "$PROJECT_DOMAIN" && validate_uuid "$VLESS_CLIENT_UUID" || fail 'Invalid saved installation state.'
    cp "$STATE_DIR/main-outbound.json" "$TEMP_DIR/main-outbound.json"
}

update_xray() {
    local installed previous candidate
    load_installation
    installed="$("$RELEASE_ROOT/current/xray" version | awk 'NR == 1 {print $2}')"
    latest_version
    if ! dpkg --compare-versions "$XRAY_VERSION" gt "$installed"; then
        printf 'Xray %s is current; no restart needed.\n' "$installed"
        return
    fi
    if [[ -f "$STATE_DIR/rejected-version" && "$(cat "$STATE_DIR/rejected-version")" == "$XRAY_VERSION" ]]; then
        fail "Xray $XRAY_VERSION failed an earlier update; waiting for a newer release."
    fi
    verify_chain || fail 'The current chain is unhealthy; update cancelled.'
    download_xray
    previous="$(readlink -f "$RELEASE_ROOT/current")"
    candidate="$TEMP_DIR/release/xray"
    if ! "$candidate" run -test -config "$CONFIG_DIR/config.json"; then
        printf '%s\n' "$XRAY_VERSION" > "$STATE_DIR/rejected-version"
        fail 'The new release rejected the configuration; the running service was not changed.'
    fi
    install_release
    switch_release "$RELEASE_ROOT/releases/$XRAY_VERSION"
    if systemctl is-failed --quiet "$SERVICE"; then
        systemctl reset-failed "$SERVICE"
    fi
    if systemctl restart "$SERVICE" && verify_chain; then
        rm -f "$STATE_DIR/rejected-version"
        printf 'Xray updated from %s to %s.\n' "$installed" "$XRAY_VERSION"
    else
        switch_release "$previous"
        printf '%s\n' "$XRAY_VERSION" > "$STATE_DIR/rejected-version"
        systemctl restart "$SERVICE" && wait_for_xray || fail 'Update and rollback failed; check the service logs.'
        fail "Xray $XRAY_VERSION failed its health check; restored $installed."
    fi
}

print_client() {
    printf '\nClient connection (client -> slave -> main):\n'
    printf 'vless://%s@%s:443?encryption=none&type=tcp&flow=xtls-rprx-vision&security=tls&sni=%s&alpn=h2&fp=firefox#slave\n' \
        "$VLESS_CLIENT_UUID" "$PROJECT_DOMAIN" "$PROJECT_DOMAIN"
    printf '\nCertificate files are retained at /etc/letsencrypt/live/%s/\n' "$PROJECT_DOMAIN"
    printf 'Check the chain: /usr/local/sbin/xray-proxy-setup --check\n'
    printf 'Service logs: journalctl -u xray-proxy -n 50 --no-pager\n'
}

main() {
    local main_exit
    case "${1:-}" in
        --help|-h)
            printf 'Usage: setup-proxy.sh [--check | --update | --help]\n'
            printf 'Install on a dedicated Debian 13 slave with its domain pointing to this server.\n'
            printf 'Allow inbound TCP 80 and 443. Provide the TLS/Vision VLESS link from main setup.sh.\n'
            return
            ;;
        ''|--check|--update) ;;
        *) fail 'Usage: setup-proxy.sh [--check | --update | --help]' ;;
    esac
    [[ $# -le 1 ]] || fail 'Too many arguments.'
    trap cleanup EXIT
    trap 'printf "\nERROR: Setup stopped at line %s. Certificates were kept.\n" "$LINENO" >&2' ERR
    preflight
    lock_setup
    if [[ "${1:-}" == --check ]]; then
        load_installation
        verify_chain || fail 'The chain check failed.'
        return
    fi
    if [[ "${1:-}" == --update ]]; then
        update_xray
        return
    fi
    check_install_target
    ask_inputs
    printf '%s\n' 'xray-proxy-setup' > "$STATE_DIR/managed"
    step 'Installing packages'
    install_packages
    step 'Checking DNS and the upstream address'
    check_domain_dns
    step 'Downloading and verifying Xray'
    latest_version
    download_xray
    step 'Checking the main VLESS connection before requesting a certificate'
    main_exit="$(probe_outbound "$TEMP_DIR/release/xray" "$TEMP_DIR/main-outbound.json")" || fail 'The main VLESS connection failed; no certificate was requested.'
    printf 'Main exit IPv4: %s\n' "$main_exit"
    step 'Configuring Nginx and checking the ACME path'
    configure_nginx
    step 'Reusing or obtaining the slave TLS certificate'
    obtain_certificate
    step 'Validating and starting the VLESS chain'
    write_xray_config
    install_service
    configure_maintenance
    print_client
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    main "$@"
fi
