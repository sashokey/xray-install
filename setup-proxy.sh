#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

export DEBIAN_FRONTEND=noninteractive
export NEEDRESTART_MODE=a

STATE_DIR="/var/lib/xray-proxy-setup"
RELEASE_ROOT="/usr/local/lib/xray-proxy"
CONFIG_DIR="/usr/local/etc/xray-proxy"
SERVICE="xray-proxy"
PROJECT_DOMAIN=""
VLESS_CLIENT_UUID=""
XRAY_VERSION=""
TEMP_DIR=""

fail() {
    printf '\nERROR: %s\n' "$1" >&2
    exit 1
}

step() {
    printf '\n==> %s\n' "$1"
}

cleanup() {
    if [[ -n "$TEMP_DIR" && -d "$TEMP_DIR" ]]; then
        rm -rf -- "$TEMP_DIR"
    fi
}

validate_domain() {
    local label
    local -a labels
    [[ ${#1} -le 253 && "$1" == *.* && "$1" != *. ]] || return 1
    IFS='.' read -r -a labels <<< "$1"
    for label in "${labels[@]}"; do
        [[ ${#label} -ge 1 && ${#label} -le 63 ]] || return 1
        [[ "$label" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ ]] || return 1
    done
    [[ "${labels[-1]}" =~ [a-z] ]]
}

validate_uuid() {
    [[ "$1" =~ ^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$ ]]
}

preflight() {
    [[ "$EUID" -eq 0 ]] || fail 'Run this script as root.'
    [[ -f /etc/os-release ]] || fail 'Cannot identify the operating system.'
    . /etc/os-release
    [[ "$ID" == debian && "$VERSION_ID" == 13 ]] || fail 'Debian 13 is required, as with setup.sh.'
    [[ -d /run/systemd/system ]] || fail 'systemd is required.'
    local program
    for program in python3 flock systemctl ip ss; do
        command -v "$program" >/dev/null || fail "Required command is missing: $program"
    done
    case "$(uname -m)" in
        x86_64|aarch64) ;;
        *) fail 'Supported architectures: x86_64 and aarch64.' ;;
    esac
}

lock_setup() {
    install -d -m 700 "$STATE_DIR"
    exec 9>"$STATE_DIR/setup.lock"
    flock -n 9 || fail 'Another proxy setup process is running.'
    TEMP_DIR="$(mktemp -d /tmp/xray-proxy-setup.XXXXXXXX)"
}

check_install_target() {
    local path port
    if [[ ! -f "$STATE_DIR/managed" ]]; then
        for path in "$CONFIG_DIR" "$RELEASE_ROOT" /etc/nginx/nginx.conf \
            /etc/systemd/system/xray-proxy.service /usr/local/sbin/xray-proxy-setup; do
            [[ ! -e "$path" && ! -L "$path" ]] || fail "Existing installation found at $path. Use a clean slave server."
        done
        for port in 80 443 8080; do
            [[ -z "$(ss -H -ltn "sport = :$port")" ]] || fail "TCP port $port is already in use."
        done
    fi
}

parse_main_link() {
    python3 - "$1" "$PROJECT_DOMAIN" <<'PY'
import ipaddress
import json
import re
import sys
import uuid
from pathlib import Path
from urllib.parse import parse_qsl, unquote, urlsplit

def reject(message):
    raise ValueError(message)

def hostname(value):
    try:
        return str(ipaddress.ip_address(value))
    except ValueError:
        labels = value.rstrip('.').lower().split('.')
        if len(value) > 253 or len(labels) < 2 or not re.search(r'[a-z]', labels[-1]):
            reject('Invalid main server hostname.')
        if any(not re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', label) for label in labels):
            reject('Invalid main server hostname.')
        return '.'.join(labels)

try:
    with open(3, encoding='utf-8', closefd=False) as source:
        link = source.read().strip()
    if len(link) > 8192 or re.search(r'\s', link) or re.search(r'%(?![0-9a-fA-F]{2})', link):
        reject('Invalid VLESS link encoding.')
    uri = urlsplit(link)
    if uri.scheme != 'vless' or not uri.username or not uri.hostname or uri.password is not None or uri.path not in ('', '/'):
        reject('Paste one complete vless:// link from setup.sh.')
    identity = unquote(uri.username, errors='strict')
    if not re.fullmatch(r'[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}', identity):
        reject('The main link must contain a UUID.')
    identity = str(uuid.UUID(identity))
    address = hostname(uri.hostname)
    port = uri.port if uri.port is not None else 443
    if not 1 <= port <= 65535:
        reject('Invalid main server port.')
    pairs = parse_qsl(uri.query, keep_blank_values=True, strict_parsing=True, errors='strict', max_num_fields=32)
    params = dict(pairs)
    if len(params) != len(pairs):
        reject('Duplicate VLESS link parameters are not supported.')
    allowed = {'security', 'flow', 'alpn', 'fp', 'type', 'encryption', 'sni', 'headerType', 'allowInsecure'}
    if set(params) - allowed:
        reject('The link contains unsupported parameters. Use the TLS/Vision link from setup.sh.')
    if params.get('security') != 'tls' or params.get('flow') != 'xtls-rprx-vision':
        reject('Expected security=tls and flow=xtls-rprx-vision, as generated by setup.sh.')
    if params.get('type', 'tcp') not in ('tcp', 'raw') or params.get('headerType', 'none') != 'none':
        reject('Only TCP/RAW without an HTTP header is supported.')
    if params.get('encryption', 'none') != 'none' or params.get('allowInsecure', '0').lower() not in ('0', 'false'):
        reject('Use encryption=none and keep TLS certificate verification enabled.')
    server_name = hostname(params.get('sni', address))
    if address == sys.argv[2] and port == 443:
        reject('Main and slave must be different servers.')
    alpn = params.get('alpn', 'h2').split(',')
    if not alpn or any(value not in ('h2', 'http/1.1') for value in alpn):
        reject('Unsupported ALPN. Expected h2 or http/1.1.')
    fingerprint = params.get('fp', 'firefox')
    if not re.fullmatch(r'[a-zA-Z0-9_-]{1,64}', fingerprint):
        reject('Invalid TLS fingerprint.')
    outbound = {
        'tag': 'main',
        'protocol': 'vless',
        'settings': {'vnext': [{
            'address': address, 'port': port,
            'users': [{'id': identity, 'encryption': 'none', 'flow': 'xtls-rprx-vision'}]
        }]},
        'streamSettings': {
            'network': 'raw', 'security': 'tls',
            'tlsSettings': {'serverName': server_name, 'alpn': alpn, 'fingerprint': fingerprint, 'allowInsecure': False}
        },
        'mux': {'enabled': False}
    }
    Path(sys.argv[1]).write_text(json.dumps(outbound, indent=2) + '\n', encoding='utf-8')
except (ValueError, UnicodeError) as error:
    print(f'ERROR: {error}', file=sys.stderr)
    sys.exit(1)
PY
}

ask_inputs() {
    local value previous='' main_link=''
    if [[ -f "$STATE_DIR/domain" ]]; then
        previous="$(cat "$STATE_DIR/domain")"
    fi
    read -r -p "Enter slave domain${previous:+ [$previous]}: " value || fail 'Input closed.'
    PROJECT_DOMAIN="${value:-$previous}"
    PROJECT_DOMAIN="${PROJECT_DOMAIN,,}"
    PROJECT_DOMAIN="${PROJECT_DOMAIN%.}"
    validate_domain "$PROJECT_DOMAIN" || fail 'Enter a valid domain without a URL scheme or path.'
    [[ -z "$previous" || "$PROJECT_DOMAIN" == "$previous" ]] || fail 'This installation already manages a different slave domain.'
    if [[ -f "$STATE_DIR/client-uuid" ]]; then
        VLESS_CLIENT_UUID="$(cat "$STATE_DIR/client-uuid")"
        validate_uuid "$VLESS_CLIENT_UUID" || fail 'Invalid saved slave UUID.'
        printf 'Reusing the saved slave UUID.\n'
    else
        read -r -p 'Slave UUID [Enter to generate]: ' VLESS_CLIENT_UUID || fail 'Input closed.'
        VLESS_CLIENT_UUID="${VLESS_CLIENT_UUID:-$(cat /proc/sys/kernel/random/uuid)}"
        validate_uuid "$VLESS_CLIENT_UUID" || fail 'Invalid UUID.'
        VLESS_CLIENT_UUID="${VLESS_CLIENT_UUID,,}"
    fi
    if [[ -f "$STATE_DIR/main-outbound.json" ]]; then
        printf 'Enter the main VLESS link, or press Enter to reuse the saved link.\n'
    fi
    read -r -s -p 'Main VLESS link (hidden): ' main_link || fail 'Input closed.'
    printf '\n'
    if [[ -z "$main_link" && -f "$STATE_DIR/main-outbound.json" ]]; then
        cp "$STATE_DIR/main-outbound.json" "$TEMP_DIR/main-outbound.json"
    else
        parse_main_link "$TEMP_DIR/main-outbound.json" 3<<< "$main_link" || fail 'The main VLESS link is not supported.'
    fi
    unset main_link
}

