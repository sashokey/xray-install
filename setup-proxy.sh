}

download_xray() {
    local arch archive expected
    case "$(uname -m)" in
        x86_64) arch=64 ;;
        aarch64) arch=arm64-v8a ;;
    esac
    archive="Xray-linux-$arch.zip"
    curl -4 --fail --show-error --location --retry 3 --connect-timeout 15 --max-time 300 \
        "https://github.com/XTLS/Xray-core/releases/download/v$XRAY_VERSION/$archive" -o "$TEMP_DIR/$archive"
    curl -4 --fail --silent --show-error --location --retry 3 --connect-timeout 15 --max-time 60 \
        "https://github.com/XTLS/Xray-core/releases/download/v$XRAY_VERSION/$archive.dgst" -o "$TEMP_DIR/$archive.dgst"
    expected="$(awk '$1 == "SHA2-256=" || $1 == "SHA256=" {print $2}' "$TEMP_DIR/$archive.dgst")"
    [[ "$expected" =~ ^[0-9a-fA-F]{64}$ ]] || fail 'The release has no valid SHA-256 checksum.'
    printf '%s  %s\n' "$expected" "$TEMP_DIR/$archive" | sha256sum -c -
    unzip -q "$TEMP_DIR/$archive" xray -d "$TEMP_DIR/release"
    [[ "$("$TEMP_DIR/release/xray" version | awk 'NR == 1 {print $2}')" == "$XRAY_VERSION" ]] || fail 'Unexpected Xray binary version.'
}

probe_outbound() {
    python3 - "$1" "$2" "$TEMP_DIR" <<'PY'
import ipaddress
import json
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

binary, source, parent = sys.argv[1:]
outbound = json.load(open(source, encoding='utf-8'))
with tempfile.TemporaryDirectory(prefix='probe-', dir=parent) as folder:
    folder = Path(folder)
    with socket.socket() as reservation:
        reservation.bind(('127.0.0.1', 0))
        port = reservation.getsockname()[1]
    config = {
        'log': {'loglevel': 'error'},
        'inbounds': [{'listen': '127.0.0.1', 'port': port, 'protocol': 'socks', 'settings': {'auth': 'noauth', 'udp': False}}],
        'outbounds': [outbound]
    }
    path = folder / 'config.json'
    path.write_text(json.dumps(config), encoding='utf-8')
    path.chmod(0o600)
    process = None
    try:
        with (folder / 'xray.log').open('w+', encoding='utf-8') as log:
            subprocess.run([binary, 'run', '-test', '-config', str(path)], stdout=log, stderr=log, check=True, timeout=15)
            process = subprocess.Popen([binary, 'run', '-config', str(path)], stdout=log, stderr=log)
            for attempt in range(100):
                if process.poll() is not None:
                    raise RuntimeError('The temporary Xray client exited.')
                try:
                    with socket.create_connection(('127.0.0.1', port), timeout=0.1):
                        break
                except OSError:
                    time.sleep(0.05)
            else:
                raise RuntimeError('The temporary Xray client did not start.')
            result = subprocess.run([
                'curl', '-4', '--fail', '--silent', '--show-error', '--noproxy', '',
                '--socks5-hostname', f'127.0.0.1:{port}', '--connect-timeout', '10', '--max-time', '25',
                'https://api.ipify.org'
            ], text=True, capture_output=True, timeout=30)
            if result.returncode:
                raise RuntimeError('The VLESS connection could not fetch https://api.ipify.org. Check main, TLS and connectivity.')
            address = ipaddress.ip_address(result.stdout.strip())
            if address.version != 4:
                raise RuntimeError('The main server did not return an IPv4 exit address.')
            print(address)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        sys.exit(1)
    finally:
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=5)
PY
}

configure_nginx() {
    local token
    install -d -m 755 /var/www/xray-proxy-acme/.well-known/acme-challenge
    if [[ -L /etc/nginx/sites-enabled/default ]]; then
        rm /etc/nginx/sites-enabled/default
    fi
    cat > "$TEMP_DIR/nginx.conf" <<EOF
server {
    listen 0.0.0.0:80;
    server_name $PROJECT_DOMAIN;
    access_log off;
    location ^~ /.well-known/acme-challenge/ {
        root /var/www/xray-proxy-acme;
        default_type text/plain;
        try_files \$uri =404;
    }
    location / {
        return 301 https://\$host\$request_uri;
    }
}
server {
    listen 127.0.0.1:8080;
    http2 on;
    server_name $PROJECT_DOMAIN;
    access_log off;
    location / {
        return 403;
    }
}
EOF
    install -m 644 "$TEMP_DIR/nginx.conf" /etc/nginx/sites-available/xray-proxy
    ln -sfn /etc/nginx/sites-available/xray-proxy /etc/nginx/sites-enabled/xray-proxy
    nginx -t
    systemctl enable nginx
    systemctl restart nginx
    token="$(cat /proc/sys/kernel/random/uuid)"
    printf '%s' "$token" > "/var/www/xray-proxy-acme/.well-known/acme-challenge/$token"
    chmod 644 "/var/www/xray-proxy-acme/.well-known/acme-challenge/$token"
    [[ "$(curl -4 --noproxy '*' --fail --silent --show-error --connect-timeout 5 --max-time 15 \
        "http://$PROJECT_DOMAIN/.well-known/acme-challenge/$token")" == "$token" ]] || fail 'The slave domain does not reach this server on TCP port 80. Check DNS and firewall rules.'
    rm "/var/www/xray-proxy-acme/.well-known/acme-challenge/$token"
}

obtain_certificate() {
    local lineage="/etc/letsencrypt/live/$PROJECT_DOMAIN" cert_key private_key
    if [[ -e "$lineage/fullchain.pem" || -e "$lineage/privkey.pem" ]]; then
        [[ -s "$lineage/fullchain.pem" && -s "$lineage/privkey.pem" ]] || fail 'The saved certificate is incomplete. Restore its files before retrying.'
        openssl x509 -in "$lineage/fullchain.pem" -noout -checkhost "$PROJECT_DOMAIN" >/dev/null || fail 'The saved certificate belongs to a different domain.'
        cert_key="$(openssl x509 -in "$lineage/fullchain.pem" -pubkey -noout)"
        private_key="$(openssl pkey -in "$lineage/privkey.pem" -pubout)"
        [[ "$cert_key" == "$private_key" ]] || fail 'The saved certificate and private key do not match.'
        if openssl x509 -in "$lineage/fullchain.pem" -noout -checkend 0 >/dev/null; then
            printf 'Reusing the existing certificate at %s; no issuance requested.\n' "$lineage"
            return
        fi
    fi
    certbot certonly --webroot -w /var/www/xray-proxy-acme \
        --non-interactive --agree-tos --register-unsafely-without-email \
        --keep-until-expiring --reuse-key --cert-name "$PROJECT_DOMAIN" -d "$PROJECT_DOMAIN"
    openssl x509 -in "$lineage/fullchain.pem" -noout -checkend 0 >/dev/null || fail 'The certificate is not valid.'
}

write_xray_config() {
    python3 - "$PROJECT_DOMAIN" "$VLESS_CLIENT_UUID" "$TEMP_DIR/main-outbound.json" "$TEMP_DIR/config.json" <<'PY'
import json
import sys
from pathlib import Path

domain, identity, main_path, target = sys.argv[1:]
main = json.load(open(main_path, encoding='utf-8'))
config = {
    'log': {'loglevel': 'warning'},
    'inbounds': [{
        'tag': 'clients', 'listen': '0.0.0.0', 'port': 443, 'protocol': 'vless',
        'settings': {
            'clients': [{'id': identity, 'flow': 'xtls-rprx-vision'}],
            'decryption': 'none', 'fallbacks': [{'dest': '127.0.0.1:8080'}]
        },
        'streamSettings': {
            'network': 'raw', 'security': 'tls',
            'tlsSettings': {'alpn': ['h2'], 'certificates': [{
                'certificateFile': f'/etc/letsencrypt/live/{domain}/fullchain.pem',
                'keyFile': f'/etc/letsencrypt/live/{domain}/privkey.pem'
            }]}
        }
    }],
    'outbounds': [main],
    'routing': {
        'domainStrategy': 'AsIs',
        'rules': [{'type': 'field', 'inboundTag': ['clients'], 'outboundTag': 'main'}]
    }
